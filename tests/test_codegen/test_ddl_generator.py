@pytest.mark.parametrize("dialect", list(SqlDialect))
def test_generate_rejects_empty_dbml(
    generator: DbmlDdlGenerator, dialect: SqlDialect
) -> None:
    """DBML rỗng bị từ chối với mã lỗi nghiệp vụ chuẩn ở mọi dialect."""
    with pytest.raises(BusinessException) as exc_info:
        generator.generate("   ", dialect)

    assert exc_info.value.code == ErrorCode.INVALID_DBML_CONTENT


def test_generated_ddl_contains_sandbox_warning_header(
    generator: DbmlDdlGenerator, ride_hailing_dbml: str
) -> None:
    """Script DDL luôn mở đầu bằng khối chú thích cảnh báo chỉ dùng cho Sandbox."""
    ddl = generator.generate(ride_hailing_dbml, SqlDialect.POSTGRESQL).ddl

    assert ddl.startswith("-- ")
    assert "không chạy trên Production" in ddl
    assert "postgresql" in ddl
