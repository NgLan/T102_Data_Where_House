DBML = """Table rides {
  ride_id int [pk, increment]
  driver_id int [not null]
  amount decimal(10,2)
}

Table drivers {
  driver_id int [pk]
  name varchar(100)
}

Ref: rides.driver_id > drivers.driver_id"""


class FakeStructuredLlm:
    def __init__(self, result=None, error: Exception | None = None) -> None:
        self.result = result
        self.error = error
        self.messages = None

    async def ainvoke(self, input):
        self.messages = input
        if self.error is not None:
            raise self.error
        return self.result


def test_postgresql_codegen_uses_identity_not_sqlite_autoincrement() -> None:
    ddl = PyDbmlArtifactGenerator().generate_ddl(DBML, "postgresql")
    assert 'CREATE TABLE "rides"' in ddl
    assert "GENERATED BY DEFAULT AS IDENTITY" in ddl
    assert "AUTOINCREMENT" not in ddl
    assert 'REFERENCES "drivers"' in ddl


def test_analysis_is_derived_from_current_tables() -> None:
    insights = PyDbmlArtifactGenerator().analyze(DBML)
    assert {item.table_name for item in insights} == {"rides", "drivers"}
    assert any(item.id == "rides:grain" for item in insights)
    assert all(item.table_name != "Fact_Rides" for item in insights)


