@pytest.mark.asyncio
async def test_llm_analysis_returns_only_grounded_confident_insights() -> None:
    llm = FakeStructuredLlm(
        LlmDataModelInsightBatch(
            insights=[
                LlmDataModelInsight(
                    id="rides:foreign-key",
                    table_name="RIDES",
                    severity="info",
                    title="Quan hệ driver hợp lệ",
                    description="Bảng rides tham chiếu bảng drivers.",
                    evidence=["rides.driver_id -> drivers.driver_id"],
                    recommendation=None,
                    confidence=0.95,
                ),
                LlmDataModelInsight(
                    id="ghost:invented",
                    table_name="ghost",
                    severity="error",
                    title="Bảng không tồn tại",
                    description="Insight này phải bị loại.",
                    confidence=0.99,
                ),
                LlmDataModelInsight(
                    id="drivers:uncertain",
                    table_name="drivers",
                    severity="warn",
                    title="Nhận xét không chắc chắn",
                    description="Insight này có confidence quá thấp.",
                    confidence=0.2,
                ),
            ]
        )
    )
    analyzer = LlmDataModelInsightAnalyzer(PyDbmlArtifactGenerator(), llm=llm)

    insights = await analyzer.analyze(DBML)

    assert [item.id for item in insights] == ["rides:foreign-key"]
    assert insights[0].table_name == "rides"
    assert "rides.driver_id -> drivers.driver_id" in insights[0].description
    assert llm.messages is not None
    assert "amount" in llm.messages[1].content


