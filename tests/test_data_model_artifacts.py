@pytest.mark.asyncio
async def test_data_model_service_returns_revision_bound_artifacts() -> None:
    model = DataModel(project_id=uuid4(), dbml=DBML, revision=7)
    repository = AsyncMock(spec=IDataModelRepository)
    repository.get_by_project_id.return_value = model
    service = DataModelService(
        repository,
        AsyncMock(spec=IUnitOfWork),
        PyDbmlArtifactGenerator(),
    )

    ddl = await service.generate_ddl(GetDataModelInput(project_id=model.project_id), "postgresql")
    insights = await service.get_insights(GetDataModelInput(project_id=model.project_id))
    assert ddl.revision == 7
    assert ddl.dialect == "postgresql"
    assert len(insights) >= 2


@pytest.mark.asyncio
async def test_data_model_service_uses_async_insight_analyzer() -> None:
    model = DataModel(project_id=uuid4(), dbml=DBML, revision=2)
    repository = AsyncMock(spec=IDataModelRepository)
    repository.get_by_project_id.return_value = model
    analyzer = AsyncMock(spec=IDataModelInsightAnalyzer)
    analyzer.analyze.return_value = [
        DataModelInsightOutput(
            id="rides:llm",
            table_name="rides",
            severity="info",
            title="LLM insight",
            description="Phân tích từ LLM.",
        )
    ]
    service = DataModelService(
        repository,
        AsyncMock(spec=IUnitOfWork),
        PyDbmlArtifactGenerator(),
        analyzer,
    )

    insights = await service.get_insights(GetDataModelInput(project_id=model.project_id))

    assert insights[0].id == "rides:llm"
    analyzer.analyze.assert_awaited_once_with(DBML)
